// T25.1 SID engine: software reference model (M1), one SID.
//
// This is the bit-level specification of the RTL in cores/trx_sid/rtl: the
// Verilator benches compare the RTL against it cycle by cycle.
//
// Provenance (docs/specs/T25.1-sid-engine.md §6):
//  - Oscillator, waveforms, noise LFSR with write-back, test bit, sync/ring,
//    floating DAC, envelope generator (LFSR rate counter, exponential counter,
//    state pipelines) and the bus value: algorithms from libresidfp/reSIDfp
//    (src/WaveformGenerator.*, EnvelopeGenerator.*, SID.cpp; Leandro Nini,
//    Antti Lankila, Dag Lem; GPL-2.0-or-later), restructured per cycle.
//  - Combined waveforms: libresidfp's WaveformCalculator tables, top 8 bits,
//    generated by gen_tables.cpp into ../mem/sid_wf_*.mem.
//  - Filter: the linear Chamberlin state-variable filter of reSID 1.0's MOS
//    8580 path (daglem/reSID src/filter.h, GPL-2.0-or-later) and its 1/Q table;
//    the cutoff comes from the app's 1024-entry curve table (spec §3.4).
//  - Waveform "zero" levels and voice DC: reSID (voice.cc, GPL-2.0-or-later).
// No UltiSID, reDIP or other HDL code was used.
//
// Deviations from reSIDfp, by design:
//  - Combined waveforms keep output bits 11..4 (low nibble 0).
//  - Oscillator sync is evaluated every cycle (reSIDfp predicts sync events;
//    the two differ only when the 6581 MSB pulldown changes the accumulator
//    between two predictions).
//  - The analog part (DAC, filter, mixer) is linear fixed point, see sidref.cpp.
#pragma once
#include <cstdint>

namespace trxsid {

struct Tables {
    uint16_t dir[4096];   // 9 bit
    uint8_t data[4096];
    bool load(const char* memdir);
    // pulldown(top 8 bits) of input wv for waveform w (combined only)
    unsigned pulldown(bool is8580, unsigned waveform, unsigned wv) const;
};

struct Wave {
    uint32_t acc = 0x555555;
    uint32_t sr = 0x7fffff;        // shift register
    uint32_t sr_latch = 0x7fffff;
    unsigned sr_pipe = 0;          // 0..2
    uint32_t noise_out = 0;        // 12 bit
    bool pulse_out = true;
    uint32_t wav_out = 0;          // 12 bit
    uint32_t tsp = 0x555;          // 8580 tri/saw pipeline
    uint32_t osc3 = 0;             // 12 bit
    uint32_t sr_reset = 0;         // test-bit shift register reset timer
    uint32_t float_ttl = 0;
    unsigned waveform = 0;         // control >> 4 as last applied
    bool test = false, sync = false, ring = false;
    bool test_or_reset = true;
    bool msb_rising = false;
};

struct Env {
    uint16_t lfsr = 0x7fff;
    unsigned rate_idx = 0;         // rate = ADSR_TABLE[rate_idx]
    unsigned exp_cnt = 0;
    unsigned exp_period = 1;
    unsigned new_exp_period = 0;
    unsigned state_pipe = 0;
    unsigned env_pipe = 0;
    unsigned exp_pipe = 0;
    unsigned state = 2;            // 0 attack, 1 decay/sustain, 2 release
    unsigned next_state = 2;
    bool counter_enabled = true;
    bool gate = false;
    bool reset_lfsr = false;
    uint8_t counter = 0xaa;
    uint8_t env3 = 0;
};

struct Config {
    bool is8580 = false;           // C64_EMUSIDn_WAVES
    bool res_high = false;         // C64_EMUSIDn_RES
    unsigned digi = 2;             // C64_EMUSIDn_DIGI 0..3
    const uint16_t* curve = nullptr; // 1024 entries (app filter curve RAM)
    // U12 (a): volts of op-amp input excursion at full scale, 0 = the linear
    // mixer of before. Only the 6581 has it.
    double opamp_drive = 0.0;
    // U12: libresidfp's cubic saturation of the waveform DAC (Dac.cpp:62-68),
    // 1.1 x - 0.11 x^3 on the unipolar DAC value. Off by default.
    bool wav_sat = false;
    // U12: libresidfp's per-voice DC, which grows with the envelope
    // (FilterModelConfig6581.cpp:181, 0.2143 V at full envelope) instead of
    // being the constant our Digis Level adds. As a fraction of full scale;
    // 0 keeps the constant.
    double voice_dc = 0.0;
};

extern const uint16_t ADSR_TABLE[16];
extern const uint16_t DIVQ_LOW[16];
extern const uint16_t DIVQ_HIGH[16];

class Sid {
public:
    explicit Sid(const Tables* t) : tab(t) {}
    Config cfg;
    uint8_t reg[32] = {0};
    Wave w[3];
    Env e[3];
    int32_t vlp = 0, vbp = 0, vhp = 0;
    uint8_t bus_value = 0;
    uint32_t bus_ttl = 0;
    uint8_t pot_x = 0xff, pot_y = 0xff;
    // per-cycle outputs of the last clock()
    int32_t vo[3] = {0, 0, 0};     // voice outputs (DCA)
    int32_t out = 0;               // 20-bit signed sample

    void reset();                  // the SID's /RES
    // CPU access in a cycle: takes effect at the next clock()
    uint8_t read(unsigned r);      // value from the current state, side effect queued
    void write(unsigned r, uint8_t v);
    void clock();

    // used by the reSIDfp comparison
    bool table_used(unsigned v) const;

private:
    const Tables* tab;
    int pend = 0;                  // 0 none, 1 write, 2 read
    unsigned pend_r = 0;
    uint8_t pend_v = 0;
    void apply_write(unsigned r, uint8_t v);
    void apply_read(unsigned r);
    void wave_ctrl(unsigned v, uint8_t control);
    void env_ctrl(unsigned v, uint8_t control);
    void env_ad(unsigned v);
    void env_sr(unsigned v);
    void shift_phase2(unsigned v, unsigned wf_old, unsigned wf_new);
    void set_noise_output(unsigned v);
    void wave_clock(unsigned v);
    void wave_output(unsigned v);
    void env_clock(unsigned v);
    void analog();
};

} // namespace trxsid
