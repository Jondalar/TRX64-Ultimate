#!/usr/bin/env python3
"""Converts the boot splash picture into C (TRX64-Ultimate docs/specs/T24-lvgl-ui.md):
software/lvgl_port/assets/trx_splash.c, which the u64ii application build picks
up by itself (target/u64ii/riscv/ultimate/Makefile, TRX_HAVE_SPLASH). The splash
(software/io/c64/trx_ui.cc) decodes it straight into the pixel layer's RGB565
frame buffers; LVGL then draws the version line on top.

    tools/splash_rle.py <splash.png> [out.c]

The picture: at most 16 colours, at most 960 x 540 (the layer; shown at 2x),
centred on black when smaller. Alpha is dropped (blended onto black first).

Format: the pixels row by row, top to bottom, as runs of one colour index:
    byte = index << 4 | n     n = 1..15: a run of n pixels
                              n = 0:     the next byte b gives a run of b + 16
                                         pixels (16..271)
A run may cross row ends; the data covers width x height pixels exactly.
The palette is RGB565 (r5 g6 b5, as the layer's format 1).

Needs python3 with PIL (Pillow). The generated file is committed: the build
container has no PIL.
"""
import os
import sys

from PIL import Image

LAYER_W, LAYER_H = 960, 540


def load(path):
    im = Image.open(path)
    if im.mode in ("RGBA", "LA", "P", "PA"):
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
        im = Image.alpha_composite(bg, im)
    return im.convert("RGB")


def rgb565(c):
    r, g, b = c
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def encode(idx):
    out = bytearray()
    i, n = 0, len(idx)
    while i < n:
        j = i
        while j < n and idx[j] == idx[i] and j - i < 271:
            j += 1
        run = j - i
        if run <= 15:
            out.append(idx[i] << 4 | run)
        else:
            out += bytes((idx[i] << 4, run - 16))
        i = j
    return out


def decode(data, count):
    idx = []
    k = 0
    while k < len(data):
        b = data[k]
        k += 1
        run = b & 15
        if run == 0:
            run = data[k] + 16
            k += 1
        idx += [b >> 4] * run
    assert len(idx) == count, (len(idx), count)
    return idx


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit("usage: tools/splash_rle.py <splash.png> [out.c]")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(
        root, "software/lvgl_port/assets/trx_splash.c")

    im = load(sys.argv[1])
    w, h = im.size
    if w > LAYER_W or h > LAYER_H:
        sys.exit("picture is %d x %d; the layer is %d x %d" % (w, h, LAYER_W, LAYER_H))
    px = list(im.getdata())
    # Black first, so index 0 is the background; the rest by first appearance.
    colours = [(0, 0, 0)] + [c for c in dict.fromkeys(px) if c != (0, 0, 0)]
    if len(colours) > 16:
        sys.exit("picture has %d colours (with black); 16 at most" % len(colours))
    pos = {c: i for i, c in enumerate(colours)}
    idx = [pos[c] for c in px]
    data = encode(idx)
    assert decode(data, w * h) == idx

    pal = [rgb565(c) for c in colours] + [0] * (16 - len(colours))
    x0, y0 = (LAYER_W - w) // 2, (LAYER_H - h) // 2
    lines = [
        "// Generated by tools/splash_rle.py from %s; do not edit." % os.path.basename(sys.argv[1]),
        "// %d x %d, %d colours, %d bytes of runs (format: tools/splash_rle.py)." % (w, h, len(colours), len(data)),
        "#include <stdint.h>",
        "",
        "const uint16_t trx_splash_w = %d, trx_splash_h = %d;" % (w, h),
        "const uint16_t trx_splash_x = %d, trx_splash_y = %d;" % (x0, y0),
        "const uint16_t trx_splash_pal[16] = {",
        "    " + ", ".join("0x%04X" % p for p in pal[:8]) + ",",
        "    " + ", ".join("0x%04X" % p for p in pal[8:]) + ",",
        "};",
        "const uint32_t trx_splash_len = %d;" % len(data),
        "const uint8_t trx_splash_rle[%d] = {" % len(data),
    ]
    for k in range(0, len(data), 24):
        lines.append("    " + ",".join("0x%02X" % b for b in data[k:k + 24]) + ",")
    lines.append("};")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("splash %d x %d, %d colours: %d bytes -> %s" % (w, h, len(colours), len(data), out))


if __name__ == "__main__":
    main()
